CATEGORY_CODE = {
    "中餐": "cn",
    "面食": "noodle",
    "小吃": "snack",
    "快餐": "fast",
    "西餐": "west",
    "日韩": "jpk",
    "汤品": "soup",
    "饮品": "drink",
    "轻食": "light",
}

VALID_TAGS = {"辣", "不辣", "荤", "素", "主食", "汤水", "小食", "饮品",
              "低卡", "重口", "下饭", "快手"}


def build():
    dishes = []
    counter = {}
    category = None
    for raw_line in RAW.strip().splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line in CATEGORY_CODE:
            category = line
            continue
        parts = line.split("|")
        if len(parts) != 5:
            raise ValueError("字段数量错误: " + line)
        name, tag_str, price, desc, reason = [p.strip() for p in parts]
        tags = [t for t in tag_str.split(",") if t]
        unknown = set(tags) - VALID_TAGS
        if unknown:
            raise ValueError("未知标签 %s: %s" % (unknown, name))
        if not tags:
            raise ValueError("缺少标签: " + name)
        code = CATEGORY_CODE[category]
        counter[code] = counter.get(code, 0) + 1
        dishes.append({
            "id": "%s_%03d" % (code, counter[code]),
            "name": name,
            "category": category,
            "tags": tags,
            "price": int(price),
            "desc": desc,
            "reason": reason,
        })

    out_dir = os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "miniprogram", "data")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "dishes.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("module.exports = ")
        json.dump(dishes, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("总数: %d" % len(dishes))
    for cat, code in CATEGORY_CODE.items():
        n = sum(1 for d in dishes if d["category"] == cat)
        print("  %s(%s): %d" % (cat, code, n))
    ids = [d["id"] for d in dishes]
    print("ID 唯一: %s" % (len(ids) == len(set(ids))))
    names = [d["name"] for d in dishes]
    dup = [n for n in set(names) if names.count(n) > 1]
    print("重名: %s" % (dup if dup else "无"))
    print("输出: %s" % out_path)


if __name__ == "__main__":
    build()
